import { useMemo, useState } from 'react';
import { useApp } from '../state';
import { formatDuration, formatNumber, stem } from '../utils';
import { Icon } from './Icon';
import { Modal } from './Modal';

export function ExportSheet() {
  const app = useApp();
  const result = app.result;
  const gcode = app.gcode;
  const [copied, setCopied] = useState(false);
  const [closing, setClosing] = useState(false);

  const lines = useMemo(() => (gcode ? gcode.split('\n') : []), [gcode]);
  const fileName = `${stem(app.model?.name ?? 'model')}.gcode`;
  const serious = result?.warnings.filter((warning) => warning.severity === 'serious') ?? [];
  const warnings = result?.warnings ?? [];
  const dialect = String(result?.settings.dialect ?? 'grbl');
  const bytes = gcode ? new TextEncoder().encode(gcode).length : 0;
  const prefix = lines.slice(0, 7).join('\n');
  const suffix = lines.slice(-5).join('\n');

  if (!result || !gcode) return null;

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(gcode);
      setCopied(true);
      app.addToast('success', 'G-code copied to the clipboard');
      window.setTimeout(() => setCopied(false), 2000);
    } catch {
      app.addToast('error', 'Could not copy', 'Your browser blocked clipboard access. Use Save instead.');
    }
  };

  const save = () => {
    setClosing(true);
    app.exportGcode();
    window.setTimeout(() => app.setExportOpen(false), 120);
  };

  return (
    <Modal
      title="Export G-code"
      subtitle="The file is generated by the same core as the command line. Nothing is uploaded."
      icon={<Icon name="download" size={20} />}
      onClose={() => app.setExportOpen(false)}
      width={660}
      footer={
        <>
          <button type="button" className="btn" onClick={() => app.setExportOpen(false)} disabled={closing}>
            Cancel
          </button>
          <button type="button" className="btn ghost" onClick={() => void copy()}>
            <Icon name={copied ? 'check' : 'code'} size={15} />
            {copied ? 'Copied' : 'Copy'}
          </button>
          <button
            type="button"
            className="btn primary"
            onClick={save}
            disabled={closing}
            title="Download the exact G-code produced by this slice"
            data-testid="export-save"
          >
            <Icon name="download" size={17} />
            {serious.length ? 'Export anyway' : 'Save G-code'}
          </button>
        </>
      }
    >
      <div className="export-summary">
        <span>
          File <b>{fileName}</b>
        </span>
        <span>
          Dialect <b>{dialect}</b>
        </span>
        <span>
          Size <b>{formatNumber(bytes)} bytes</b>
        </span>
        <span>
          Lines <b>{formatNumber(lines.length)}</b>
        </span>
      </div>

      {app.stale ? (
        <div className="warning-callout">
          <Icon name="warning" size={16} />
          <span>
            Settings have changed since this slice. The file will be exactly what is shown here, not
            the new settings. Slice again to apply the changes.
          </span>
        </div>
      ) : null}

      {serious.length ? (
        <div className="warning-callout" role="alert">
          <Icon name="warning" size={16} />
          <span>
            {serious.length} serious printability warning{serious.length === 1 ? '' : 's'} remain
            {serious.length === 1 ? 's' : ''}. Export is allowed; review the Inspector first.
          </span>
        </div>
      ) : warnings.length ? (
        <div className="warning-callout" style={{ color: 'var(--text2)' }}>
          <Icon name="info" size={16} />
          <span>
            {warnings.length} advisory note{warnings.length === 1 ? '' : 's'}. They do not block
            export.
          </span>
        </div>
      ) : null}

      <div className="form-grid" style={{ marginBottom: 12 }}>
        <div>
          <div className="field-label">
            <span>Start code</span>
          </div>
          <pre className="code-preview" aria-label="Start code preview">
            {prefix || '—'}
          </pre>
        </div>
        <div>
          <div className="field-label">
            <span>End code</span>
          </div>
          <pre className="code-preview" aria-label="End code preview">
            {suffix || '—'}
          </pre>
        </div>
      </div>

      <div className="export-facts">
        <span>
          <Icon name="clock" size={13} /> Estimated {formatDuration(result.stats.time_s)}
        </span>
        <span>
          <Icon name="layers" size={13} /> {result.layers} layers
        </span>
        <span>
          <Icon name="pump" size={13} /> {result.stats.gel_ml.toFixed(3)} mL gel
        </span>
        <span>
          <Icon name="activity" size={13} /> {formatNumber(result.stats.points)} points
        </span>
      </div>
    </Modal>
  );
}